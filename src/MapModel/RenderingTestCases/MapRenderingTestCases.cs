        // A test that may run beside other tests.
        // name: the name of the test.
        // checks: the checks it makes, in order.
        private static MapRenderingTestCase Test(string name, params MapRenderingCheck[] checks)
        {
            return new MapRenderingTestCase(name, false, checks);
        }

        // A test that must not run beside other tests.
        // name: the name of the test.
        // checks: the checks it makes, in order.
        private static MapRenderingTestCase NonParallelizableTest(string name, params MapRenderingCheck[] checks)
        {
            return new MapRenderingTestCase(name, true, checks);
        }
